import os
import shutil
import subprocess
from pathlib import Path, PurePath

from pydantic import BaseModel, ConfigDict

INCLUDE = "Include ~/.microsandbox-studio/ssh_config"
NO_WINDOW = getattr(subprocess, "CREATE_NO_WINDOW", 0)


class Paths(BaseModel):
    model_config = ConfigDict(frozen=True)

    home: Path
    msb: Path

    @property
    def config(self) -> Path:
        return self.home / ".microsandbox-studio" / "ssh_config"

    @property
    def key(self) -> Path:
        return self.home / ".microsandbox-studio" / "ssh" / "id_ed25519"

    @property
    def user_config(self) -> Path:
        return self.home / ".ssh" / "config"


def alias(name: str) -> str:
    return f"{name}.msb"


def _config_path(path: PurePath) -> str:
    if '"' in str(path):
        raise ValueError(f"Paths with double quotes are not supported: {path}")
    return '"' + path.as_posix().replace("%", "%%") + '"'


def host_entry(paths: Paths, name: str) -> str:
    return "\n".join(
        [
            f"Host {alias(name)}",
            "  User root",
            f"  ProxyCommand {_config_path(paths.msb)} ssh serve --stdio --no-inactivity-timeout {name}",
            f"  IdentityFile {_config_path(paths.key)}",
            "  IdentitiesOnly yes",
            "  StrictHostKeyChecking no",
            f"  UserKnownHostsFile {os.devnull}",
            "  LogLevel ERROR",
        ]
    )


def render_config(paths: Paths, names: list[str]) -> str:
    header = "# Generated by Microsandbox Studio from its sandbox list; changes are overwritten.\n"
    return header + "".join(f"\n{host_entry(paths, name)}\n" for name in sorted(names))


def is_set_up(paths: Paths) -> bool:
    return paths.config.exists() and paths.key.exists()


def is_included(paths: Paths) -> bool:
    lines = paths.user_config.read_text().splitlines() if paths.user_config.exists() else []
    return INCLUDE.lower() in (line.strip().lower() for line in lines)


def _write(path: Path, text: str, mode: int) -> None:
    path.parent.mkdir(parents=True, exist_ok=True, mode=0o700)
    temporary = path.with_name(f".{path.name}.tmp")
    temporary.write_text(text)
    temporary.chmod(mode)
    os.replace(temporary, path)


def write_config(paths: Paths, names: list[str]) -> None:
    if not paths.config.exists():
        return
    text = render_config(paths, names)
    if paths.config.read_text() != text:
        _write(paths.config, text, 0o600)


def set_up(paths: Paths, names: list[str]) -> None:
    _authorize(paths)
    _write(paths.config, render_config(paths, names), 0o600)


def remove(paths: Paths) -> None:
    shutil.rmtree(paths.config.parent, ignore_errors=True)


def _authorize(paths: Paths) -> None:
    if not paths.key.exists():
        paths.key.parent.mkdir(parents=True, exist_ok=True, mode=0o700)
        subprocess.run(
            ["ssh-keygen", "-q", "-t", "ed25519", "-N", "", "-C", "microsandbox-studio", "-f", str(paths.key)],
            check=True,
            capture_output=True,
            stdin=subprocess.DEVNULL,
            creationflags=NO_WINDOW,
        )
    result = subprocess.run(
        [str(paths.msb), "ssh", "authorize", "--file", f"{paths.key}.pub"],
        check=False,
        capture_output=True,
        text=True,
        stdin=subprocess.DEVNULL,
        creationflags=NO_WINDOW,
    )
    if result.returncode:
        raise RuntimeError(f"msb ssh authorize failed: {result.stderr.strip() or result.stdout.strip()}")
